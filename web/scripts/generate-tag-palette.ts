import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { formatHex, parse } from 'culori';

// Writes the sRGB color of every Tailwind palette color a tag can have, twice: src/lib/tags/palette.generated.ts, which
// the contrast ratios in the color picker are computed from (a ratio is computed in code, not by the browser), and
// src/lib/tags/palette.generated.css, custom properties (`--tag-color-emerald-200`) that a chip paints with. The same
// values in both, so the ratio shown is the one of the colors painted. They are not Tailwind theme variables: those
// are only emitted when a class uses them, and redefining them would change every `bg-emerald-200` on the site.
//   bun scripts/generate-tag-palette.ts        (`mise web:palette` runs it, then formats the output)
// Tailwind v4 states its palette in OKLCH (node_modules/tailwindcss/theme.css), so culori converts each to sRGB, clipped
// to the gamut and rounded to the 8 bits a browser paints, which is what Chrome paints too (tests/palette.test.ts
// compares them in a canvas). Rerun it after upgrading Tailwind, and check `bun test`, which compares the families
// with the database domain.
const web = join(import.meta.dirname, '..');
const theme = readFileSync(join(web, 'node_modules', 'tailwindcss', 'theme.css'), 'utf8');
const outputTs = join(web, 'src', 'lib', 'tags', 'palette.generated.ts');
const outputCss = join(web, 'src', 'lib', 'tags', 'palette.generated.css');

const colors: Record<string, string> = { black: '#000000', white: '#ffffff' };
for (const match of theme.matchAll(/--color-([a-z]+-\d+):\s*(oklch\([^)]*\))/g)) {
  const [, name, css] = match;
  if (name === undefined || css === undefined) continue;
  const color = parse(css);
  if (color === undefined) throw new Error(`culori cannot read ${css} (${name}) in tailwindcss/theme.css`);
  colors[name] = formatHex(color);
}

const lines = Object.entries(colors).map(([name, hex]) => `  '${name}': '${hex}',`);
const properties = Object.entries(colors).map(([name, hex]) => `  --tag-color-${name}: ${hex};`);
writeFileSync(
  outputCss,
  `/* Generated by scripts/generate-tag-palette.ts from tailwindcss/theme.css. Do not edit. */\n\n:root {\n${properties.join('\n')}\n}\n`,
);
writeFileSync(
  outputTs,
  `// Generated by scripts/generate-tag-palette.ts from tailwindcss/theme.css. Do not edit.\n\n` +
    `/** The sRGB hex of each Tailwind palette color, by the name a tag stores. */\n` +
    `export const palette: Readonly<Record<string, string>> = {\n${lines.join('\n')}\n};\n`,
);
console.log(`Wrote ${Object.keys(colors).length.toString()} colors to src/lib/tags/palette.generated.{ts,css}`);

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { key, newUses, refName, shapeOf, type Schema } from './shapes.ts';

// Writes the API client from the API's OpenAPI document:
//   bun scripts/generate-api-client.ts <openapi.json> <output directory>        (`mise api:openapi` runs it)
// One module per controller, with one standalone function per action, so a route that calls `tag.get` ships `tag.get` and
// nothing else (an unused function tree-shakes away, and an admin-only one is only in admin routes' chunks).
//   tag.ts           export function getAll(options?), get(params, options?), create(body, options?), ...
//   index.ts         export * as tag from './tag.ts'; ...
// A function takes its path and query parameters as one object, then the body, then `CallOptions`, and leaves out
// whichever the action does not have. It calls the runtime's function for its method (`http.get`, `http.post`, ...)
// with the options first, then the operation's name, its route (the path parameters filled in by `route`), and only then
// what the method takes (a body, the shape of a response that has instants, a query), so it passes `undefined` for one
// it does not have only to reach one after it. What comes back is not passed: the runtime reads it from the response.
// The runtime is hand-written (./runtime), and so are the types it returns (schema.ts, from
// scripts/generate-api-types.ts, which also writes the shape of each schema that has an instant in it). Needs each
// operation's `operationId` to be `controller.action`.

const GENERATED = "// Generated by scripts/generate-api-client.ts from the API's OpenAPI document. Do not edit.";
const METHODS = ['get', 'put', 'post', 'delete', 'patch'] as const;
// What a function must not be called, as well as a reserved word: what the module imports, and the parameters of every
// function in it (an action named `options` would be shadowed by each `options?: CallOptions`). Such an action is
// declared as `options$` and exported as `options`.
const TAKEN_NAMES = new Set(['http', 'route', 'params', 'body', 'options']);
const RESERVED = new Set(
  (
    'await break case catch class const continue debugger default delete do else enum export extends false finally for ' +
    'function if import in instanceof new null return super switch this throw true try typeof var void while with yield ' +
    'let static implements interface package private protected public arguments eval'
  ).split(' '),
);

type Parameter = { name: string; in: string; required?: boolean; description?: string; schema: Schema };
type Content = Record<string, { schema?: Schema }>;
type Response = { description?: string; content?: Content };
type Operation = {
  operationId?: string;
  summary?: string;
  description?: string;
  parameters?: Parameter[];
  requestBody?: { description?: string; required?: boolean; content?: Content };
  responses: Record<string, Response>;
};
type Document = {
  paths: Record<string, Partial<Record<(typeof METHODS)[number] | 'query', Operation>>>;
  components?: { schemas?: Record<string, Schema> };
};

// What a module uses: schema types, shape constants it refers to (a schema's name is a type and a value), and the runtime.
type Imports = { types: Set<string>; values: Set<string>; runtime: Set<string> };

type Generated = { controller: string; file: string; name: string; code: string };

const [documentPath, outputDirectory] = process.argv.slice(2);
if (documentPath === undefined || outputDirectory === undefined) {
  throw new Error('Usage: bun scripts/generate-api-client.ts <openapi.json> <output directory>');
}
const document: Document = JSON.parse(readFileSync(documentPath, 'utf8'));
const schemas = document.components?.schemas ?? {};

// ---- reading the document -------------------------------------------------------------------------------------------

type Found = {
  id: string;
  controller: string;
  action: string;
  method: (typeof METHODS)[number];
  path: string;
  op: Operation;
};

function findOperations(): Found[] {
  const found: Found[] = [];
  const seen = new Set<string>();
  for (const [path, item] of Object.entries(document.paths)) {
    if (item.query !== undefined) throw new Error(`${path}: a QUERY operation is not supported yet`);
    for (const method of METHODS) {
      const op = item[method];
      if (op === undefined) continue;
      const id = op.operationId ?? '';
      const match = /^([a-z][A-Za-z0-9]*)\.([a-z][A-Za-z0-9]*)$/.exec(id);
      if (match === null)
        throw new Error(`${method.toUpperCase()} ${path}: operationId "${id}" is not controller.action`);
      if (seen.has(id)) throw new Error(`operationId "${id}" is used twice`);
      seen.add(id);
      found.push({ id, controller: match[1], action: match[2], method, path, op });
    }
  }
  return found;
}

// ---- types ----------------------------------------------------------------------------------------------------------

function typeOf(schema: Schema, where: string, imports: Imports): string {
  if (schema.$ref !== undefined) {
    const name = refName(schema.$ref);
    if (!(name in schemas)) throw new Error(`${where}: ${schema.$ref} is not in the document`);
    imports.types.add(name);
    return name;
  }
  const union = schema.oneOf ?? schema.anyOf;
  if (union !== undefined) return [...new Set(union.map((member) => typeOf(member, where, imports)))].join(' | ');
  const [only] = schema.allOf ?? [];
  if (only !== undefined && schema.allOf?.length === 1) return typeOf(only, where, imports);

  const types = Array.isArray(schema.type) ? schema.type : schema.type === undefined ? [] : [schema.type];
  if (types.length === 0) return 'unknown';
  return [...new Set(types.map((type) => typeNamed(type, schema, where, imports)))].join(' | ');
}

function typeNamed(type: string, schema: Schema, where: string, imports: Imports): string {
  switch (type) {
    case 'null':
      return 'null';
    case 'boolean':
      return 'boolean';
    case 'integer':
    case 'number':
      return 'number';
    case 'string':
      if (schema.format === 'date-time') {
        imports.types.add('Instant');
        return 'Instant';
      }
      return 'string';
    case 'array':
      return `${wrap(typeOf(schema.items ?? {}, where, imports))}[]`;
    case 'object':
      return objectType(schema, where, imports);
    default:
      throw new Error(`${where}: unsupported type "${type}"`);
  }
}

function objectType(schema: Schema, where: string, imports: Imports): string {
  if (schema.properties !== undefined) {
    const required = new Set(schema.required ?? []);
    const members = Object.entries(schema.properties).map(
      ([name, member]) => `${key(name)}${required.has(name) ? '' : '?'}: ${typeOf(member, where, imports)}`,
    );
    return `{ ${members.join('; ')} }`;
  }
  const extra = schema.additionalProperties;
  if (extra !== undefined && extra !== false) {
    return `Record<string, ${extra === true ? 'unknown' : typeOf(extra, where, imports)}>`;
  }
  return 'Record<string, unknown>';
}

// An array of a union needs its parentheses: `(A | B)[]`.
const wrap = (type: string): string => (type.includes(' | ') ? `(${type})` : type);

// ---- one operation --------------------------------------------------------------------------------------------------

function describe(found: Found, imports: Imports, usedNames: Set<string>): string {
  const { id, method, op } = found;
  const parameters = (op.parameters ?? [])
    .filter((parameter) => parameter.in === 'path' || parameter.in === 'query')
    .toSorted((a, b) => Number(b.in === 'path') - Number(a.in === 'path'));
  const names = parameters.map((parameter) => parameter.name);
  if (new Set(names).size !== names.length) throw new Error(`${id}: a path and a query parameter share a name`);

  const body = op.requestBody;
  const bodySchema = body?.content?.['application/json']?.schema;
  if (body !== undefined && bodySchema === undefined)
    throw new Error(`${id}: the request body is not application/json`);

  const success = Object.entries(op.responses)
    .filter(([status]) => status.startsWith('2'))
    .toSorted(([a], [b]) => a.localeCompare(b))[0];
  if (success === undefined) throw new Error(`${id}: no 2xx response`);
  const [successStatus, successResponse] = success;
  const replySchema = successResponse.content?.['application/json']?.schema;
  const returns =
    replySchema !== undefined
      ? typeOf(replySchema, id, imports)
      : successStatus === '201'
        ? imports.types.add('Created') && 'Created'
        : 'void';

  // Where the response has instants: the constant of a schema, or of a list of one, which schema.ts has built.
  const uses = newUses();
  const shape = replySchema === undefined ? undefined : shapeOf(replySchema, schemas, id, uses, new Set());
  if (shape !== undefined && (shape === 'instant' || !/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(shape))) {
    throw new Error(`${id}: the response is not a schema, or an array of one, so its shape has no constant: ${shape}`);
  }
  for (const name of uses.runtime) imports.runtime.add(name);
  if (shape !== undefined) imports.values.add(shape);

  // The parameters of the function, in order: params, body, options.
  const args: string[] = [];
  if (parameters.length > 0) {
    const members = parameters.map(
      (parameter) =>
        `${key(parameter.name)}${parameter.required === true ? '' : '?'}: ${typeOf(parameter.schema, id, imports)}`,
    );
    // An optional parameter cannot come before a required one, so a required body makes the parameters required too.
    const optional = !parameters.some((parameter) => parameter.required === true) && body?.required !== true;
    args.push(`params${optional ? '?' : ''}: { ${members.join('; ')} }`);
  }
  if (bodySchema !== undefined)
    args.push(`body${body?.required === true ? '' : '?'}: ${typeOf(bodySchema, id, imports)}`);
  args.push('options?: TOptions');
  imports.runtime.add('CallOptions');
  imports.runtime.add('ApiPromise');
  if (returns === 'Created') imports.runtime.add('Created');

  const local = RESERVED.has(found.action) || TAKEN_NAMES.has(found.action) ? `${found.action}$` : found.action;
  if (usedNames.has(local)) throw new Error(`${id}: ${local} is already a function in this module`);
  usedNames.add(local);

  const path = routeOf(found, parameters, imports);
  const query = queryOf(parameters, args[0]?.startsWith('params?'));
  // After the route: a body (only for a method that has one), the shape, and the query. Each missing one is passed as
  // `undefined` only when one after it is passed.
  const takesBody = method !== 'get' && method !== 'delete';
  const slots = takesBody ? [bodySchema === undefined ? undefined : 'body', shape, query] : [shape, query];
  const last = slots.findLastIndex((slot) => slot !== undefined);
  const trailing = slots.slice(0, last + 1).map((slot) => slot ?? 'undefined');

  const exportLine = local === found.action ? '' : `\nexport { ${local} as ${found.action} };`;
  const call = ['options', `'${id}'`, path, ...trailing].join(', ');
  return (
    `${docs(found, parameters, returns, successResponse)}\n` +
    `export function ${local}<TOptions extends CallOptions>(${args.join(', ')}): ApiPromise<${returns}, TOptions> {\n` +
    `  return http.${method}<${returns}>(${call});\n` +
    `}${exportLine}\n`
  );
}

// The route as code: a plain string, or `route` over a template with each path parameter in it.
function routeOf(found: Found, parameters: Parameter[], imports: Imports): string {
  const { id, path } = found;
  if (/[`$\\]/.test(path)) throw new Error(`${id}: ${path} has a character the generator does not escape`);
  const pathNames = new Set(
    parameters.filter((parameter) => parameter.in === 'path').map((parameter) => parameter.name),
  );
  const named = [...path.matchAll(/\{([^}]+)\}/g)].map((match) => match[1] ?? '');
  if (named.length !== pathNames.size || named.some((name) => !pathNames.has(name))) {
    throw new Error(`${id}: the parameters of ${path} are not the path parameters`);
  }
  if (named.length === 0) return `'${path}'`;
  imports.runtime.add('route');
  return `route\`${path.replace(/\{([^}]+)\}/g, (_match, name: string) => `\${${access('params', name)}}`)}\``;
}

// The query parameters as an object, or undefined when there are none.
function queryOf(parameters: Parameter[], optionalParams: boolean | undefined): string | undefined {
  const names = parameters.filter((parameter) => parameter.in === 'query').map((parameter) => parameter.name);
  if (names.length === 0) return undefined;
  const from = optionalParams ? 'params?' : 'params';
  return `{ ${names.map((name) => `${key(name)}: ${access(from, name)}`).join(', ')} }`;
}

// `params.page` (or `params?.page`), or `params['a-b']` when the name is not an identifier.
function access(from: string, name: string): string {
  const optional = from.endsWith('?');
  const base = optional ? from.slice(0, -1) : from;
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name)
    ? `${from}.${name}`
    : `${base}${optional ? '?.' : ''}[${JSON.stringify(name)}]`;
}

// ---- documentation --------------------------------------------------------------------------------------------------

function docs(found: Found, parameters: Parameter[], returns: string, success: Response): string {
  const { op, method, path } = found;
  const lines: string[] = [];
  if (op.summary !== undefined) lines.push(...op.summary.split('\n'));
  if (op.description !== undefined) lines.push('', ...op.description.split('\n'));

  const tags: string[] = [];
  for (const parameter of parameters) {
    tags.push(`@param params.${parameter.name} ${parameter.description ?? ''}`.trimEnd());
  }
  if (op.requestBody !== undefined) tags.push(`@param body ${op.requestBody.description ?? ''}`.trimEnd());
  // "OK" is ASP.NET's own description for a response nobody wrote one for, and says nothing.
  if (returns !== 'void' && success.description !== undefined && success.description !== 'OK') {
    tags.push(`@returns ${success.description}`);
  }
  for (const [status, response] of Object.entries(op.responses)) {
    if (!status.startsWith('2')) tags.push(`@throws {ApiError} ${status}: ${response.description ?? ''}`.trimEnd());
  }
  if (tags.length > 0) lines.push('', ...tags);
  lines.push('', `\`${method.toUpperCase()} ${path}\``);
  return `/**\n${lines
    .map((line) => ` * ${line}`.trimEnd())
    .join('\n')
    .replaceAll('*/', '*\\/')}\n */`;
}

// ---- files ----------------------------------------------------------------------------------------------------------

const kebab = (name: string): string => name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

function generateController(controller: string, operations: Found[]): Generated {
  const imports: Imports = { types: new Set(), values: new Set(), runtime: new Set(['http']) };
  const usedNames = new Set<string>();
  const functions = operations.map((found) => describe(found, imports, usedNames));

  const runtimeNames = [...imports.runtime].toSorted();
  const runtimeTypes = new Set(['CallOptions', 'Created', 'ApiPromise']);
  const runtimeImport = runtimeNames.map((name) => (runtimeTypes.has(name) ? `type ${name}` : name)).join(', ');
  // `Created` is a runtime type, not one of the schema's. A name that is a value is imported as one, which brings its type.
  const schemaNames = [...new Set([...imports.types, ...imports.values])]
    .filter((name) => name !== 'Created')
    .toSorted();
  const schemaImport = schemaNames.map((name) => (imports.values.has(name) ? name : `type ${name}`)).join(', ');
  const header = [
    GENERATED,
    ...(schemaNames.length === 0 ? [] : [`import { ${schemaImport} } from './schema.ts';`]),
    `import { ${runtimeImport} } from './runtime/index.ts';`,
  ];
  const file = `${kebab(controller)}.ts`;
  return { controller, file, name: controller, code: `${header.join('\n')}\n\n${functions.join('\n')}` };
}

const byController = new Map<string, Found[]>();
for (const found of findOperations())
  byController.set(found.controller, [...(byController.get(found.controller) ?? []), found]);
const generated = [...byController].map(([controller, operations]) => generateController(controller, operations));

const index = [
  GENERATED,
  ...generated.toSorted((a, b) => a.name.localeCompare(b.name)).map((g) => `export * as ${g.name} from './${g.file}';`),
  '',
  "export { ApiError, nullOnApiError, type CallOptions, type Created, type Problem } from './runtime/index.ts';",
  '',
].join('\n');

mkdirSync(outputDirectory, { recursive: true });
// What an earlier run wrote and this one does not (a controller that is gone) is removed.
const keep = new Set([...generated.map((g) => g.file), 'index.ts']);
for (const file of readdirSync(outputDirectory)) {
  const path = join(outputDirectory, file);
  if (file.endsWith('.ts') && !keep.has(file) && existsSync(path) && readFileSync(path, 'utf8').startsWith(GENERATED)) {
    rmSync(path);
  }
}
for (const g of generated) writeFileSync(join(outputDirectory, g.file), g.code);
writeFileSync(join(outputDirectory, 'index.ts'), index);

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { accountLayer, publicKeyOf, type TestAccount } from './account.ts';

// Makes the account the browser tests start from (ADR 0033, a scoped database per test): a user with one passkey whose
// private key a test can give to Chromium's virtual authenticator, so it signs in with the real ceremony. Writes two
// files that go together, so rerunning it changes both:
//   JoshOlson.Database/seeds/account.yaml        the `account` layer: the user and the passkey row, with the public key
//   web/tests/support/account.generated.ts       the private key and the IDs the authenticator is given
// The key is made up here and means nothing anywhere else: it is bound to the relying party `localhost`, and it is
// committed on purpose, like the layers (scripts/account.test.ts checks that the two halves still belong together).
//   bun scripts/generate-test-account.ts        (`mise web:account` runs it, then formats the output)
const repository = join(import.meta.dirname, '..', '..');

const pair = await crypto.subtle.generateKey({ name: 'ECDSA', namedCurve: 'P-256' }, true, ['sign', 'verify']);
const account: TestAccount = {
  displayName: 'E2E Admin',
  nickname: 'First key',
  userHandle: crypto.getRandomValues(new Uint8Array(32)),
  credentialId: crypto.getRandomValues(new Uint8Array(32)),
  privateKey: new Uint8Array(await crypto.subtle.exportKey('pkcs8', pair.privateKey)),
};
const base64 = (bytes: Uint8Array): string => Buffer.from(bytes).toString('base64');

writeFileSync(
  join(repository, 'JoshOlson.Database', 'seeds', 'account.yaml'),
  accountLayer(account, await publicKeyOf(account.privateKey)),
);
writeFileSync(
  join(repository, 'web', 'tests', 'support', 'account.generated.ts'),
  `// Generated by scripts/generate-test-account.ts, with the account layer (JoshOlson.Database/seeds/account.yaml). Do not edit.
// A development credential: the private key of the passkey in that layer, for Chromium's virtual authenticator.

/** The account in the \`account\` layer, and the passkey of its one key. Everything is base64, as CDP takes it. */
export const account = {
  displayName: ${JSON.stringify(account.displayName)},
  nickname: ${JSON.stringify(account.nickname)},
  relyingPartyId: 'localhost',
  userHandle: ${JSON.stringify(base64(account.userHandle))},
  credentialId: ${JSON.stringify(base64(account.credentialId))},
  privateKey: ${JSON.stringify(base64(account.privateKey))},
} as const;
`,
);

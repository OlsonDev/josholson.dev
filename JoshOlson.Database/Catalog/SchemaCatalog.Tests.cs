  [Theory]
  [InlineData("interval", "interval")]
  [InlineData("uuid", "uuid")]
  [InlineData("character varying(20)", "character varying(20)")]
  [InlineData("timestamp without time zone", "timestamp without time zone")]
  [InlineData("timestamp(3) with time zone", "timestamp(3) with time zone")]
  public async Task ReadAsync_UnsupportedColumnType_ThrowsNamingTheColumnAndTheType(string declared, string shown) {
    var ddl = $"CREATE SCHEMA {{schema}}; CREATE TABLE {{schema}}.bar (baz INT NOT NULL, qux {declared} NULL);";

    var exception = await Assert.ThrowsAsync<SchemaCatalogException>(()
      => InScratchSchemaAsync(ddl, async name => await ReadAsync(new() { OnlySchemas = [name] })));

    Assert.Contains(".bar.qux", exception.Message, StringComparison.Ordinal);
    Assert.Contains($"'{shown}'", exception.Message, StringComparison.Ordinal);
  }

  [Fact]
  public async Task ReadAsync_SeveralProblems_AreAllReportedTogether() {
    const string Ddl = """
      CREATE SCHEMA {schema};
      CREATE DOMAIN {schema}.span AS interval;
      CREATE TABLE {schema}.bar (baz uuid NULL, qux INT NULL, quux timestamptz NULL);
      COMMENT ON COLUMN {schema}.bar.qux IS '@seed absolute';
      COMMENT ON COLUMN {schema}.bar.quux IS '@seed sometimes';
      """;

    var exception = await Assert.ThrowsAsync<SchemaCatalogException>(()
      => InScratchSchemaAsync(Ddl, async name => await ReadAsync(new() { OnlySchemas = [name] })));

    Assert.Equal(4, exception.Problems.Count);
    Assert.Contains(exception.Problems, problem => problem.Contains(".span", StringComparison.Ordinal));
    Assert.Contains(exception.Problems, problem => problem.Contains(".bar.baz", StringComparison.Ordinal));
    Assert.Contains(exception.Problems, problem => problem.Contains(".bar.qux", StringComparison.Ordinal));
    Assert.Contains(exception.Problems, problem => problem.Contains(".bar.quux", StringComparison.Ordinal));
  }


  [Theory]
  [InlineData("seen_utc timestamptz", "@seed sometimes")]
  [InlineData("seen_utc timestamptz", "@seed")]
  [InlineData("seen_utc timestamptz", "@seed relative @seed absolute")]
  [InlineData("count INT", "@seed absolute")]
  public async Task ReadAsync_BadSeedDirective_ThrowsNamingTheColumn(string column, string comment) {
    var name = column.Split(' ')[0];
    var ddl = $"CREATE SCHEMA {{schema}}; CREATE TABLE {{schema}}.bar ({column} NULL); COMMENT ON COLUMN {{schema}}.bar.{name} IS '{comment}';";

    var exception = await Assert.ThrowsAsync<SchemaCatalogException>(()
      => InScratchSchemaAsync(ddl, async schema => await ReadAsync(new() { OnlySchemas = [schema] })));

    Assert.Contains($".bar.{name}", exception.Message, StringComparison.Ordinal);
  }


// Reads the dev database (start and migrate it first, see CLAUDE.md). The scratch tests create a schema of their own as
// the owner, read just that, and drop it, so they run one after another in this class and never disturb the real schemas.
public class SchemaCatalogTests {
  private const string _ScratchDdl = """
    CREATE SCHEMA {schema};
    COMMENT ON SCHEMA {schema} IS 'Scratch things';
    CREATE DOMAIN {schema}.name_text AS text NOT NULL DEFAULT 'x' CHECK (VALUE != '');
    COMMENT ON DOMAIN {schema}.name_text IS 'Non-empty text';
    CREATE DOMAIN {schema}.coords AS numeric(9, 6) CHECK (VALUE BETWEEN -180 AND 180);
    CREATE DOMAIN {schema}.tag_ids AS smallint[];
    CREATE DOMAIN {schema}.short_name AS {schema}.name_text CHECK (length(VALUE) <= 20);
    CREATE TABLE {schema}.foo (
        foo_id     INT                             NOT NULL GENERATED ALWAYS AS IDENTITY
      , width      INT                             NOT NULL DEFAULT 7
      , area       INT                             GENERATED ALWAYS AS (width * 2) STORED
      , twice      INT                             GENERATED ALWAYS AS (width * 2) VIRTUAL
      , label      INT                             NOT NULL GENERATED BY DEFAULT AS IDENTITY
      , name       {schema}.name_text
      , nick       {schema}.short_name
      , lat        {schema}.coords
      , price      numeric(12, 2)
      , amount     numeric
      , prices     numeric(5, 1)[]
      , tags       {schema}.tag_ids
      , seen_utc   timestamp with time zone
      , stamps     timestamp with time zone[]
      , fixed_utc  timestamptz
      , CONSTRAINT pk_foo PRIMARY KEY (foo_id)
      , CONSTRAINT uq_foo_width UNIQUE (width)
      , CONSTRAINT ck_foo_width CHECK (width > 0)
    );
    CREATE INDEX ix_foo_width ON {schema}.foo (width) WHERE width > 1;
    COMMENT ON TABLE {schema}.foo IS 'The foo';
    COMMENT ON COLUMN {schema}.foo.fixed_utc IS 'When it happened. @seed absolute';
    CREATE TABLE {schema}.link (
        foo_id    INT  NOT NULL
      , ref_id    INT  NOT NULL
      , other_id  INT      NULL
      , CONSTRAINT pk_link PRIMARY KEY (ref_id, foo_id)
      , CONSTRAINT fk_link__foo FOREIGN KEY (foo_id) REFERENCES {schema}.foo (foo_id) ON DELETE CASCADE ON UPDATE RESTRICT DEFERRABLE INITIALLY DEFERRED
      , CONSTRAINT fk_link__other FOREIGN KEY (other_id) REFERENCES {schema}.foo (foo_id) ON DELETE SET NULL
    );
    CREATE TABLE {schema}.loose (
        note  TEXT  NULL
    );
    """;

  private readonly CancellationToken _cancellationToken = TestContext.Current.CancellationToken;

  private static string ConnectionString() {
    var password = Environment.GetEnvironmentVariable("POSTGRES_PASSWORD")
      ?? throw new InvalidOperationException("POSTGRES_PASSWORD is not set. Start and migrate the dev database and run the tests with `mise run test`, which reads .env.");
    return new NpgsqlConnectionStringBuilder {
      Host = "127.0.0.1",
      Port = int.Parse(Environment.GetEnvironmentVariable("POSTGRES_PORT") ?? "5432", CultureInfo.InvariantCulture),
      Username = Environment.GetEnvironmentVariable("POSTGRES_USER") ?? "josholson",
      Password = password,
      Database = Environment.GetEnvironmentVariable("POSTGRES_DB") ?? "josholson",
      SslMode = SslMode.Disable,
    }.ToString();
  }

  private async Task<CatalogSchema> ReadAsync(CatalogOptions? options = null) {
    await using NpgsqlConnection connection = new(ConnectionString());
    await connection.OpenAsync(_cancellationToken);
    return await SchemaCatalog.ReadAsync(connection, options ?? new(), _cancellationToken);
  }

  // Runs `ddl` (with {schema} filled in) in a schema of its own, passes the schema's name on, and drops it afterwards.
  private async Task<T> InScratchSchemaAsync<T>(string ddl, Func<string, Task<T>> body) {
    var schema = $"catalog_test_{Guid.NewGuid():N}";
    await using NpgsqlConnection connection = new(ConnectionString());
    await connection.OpenAsync(_cancellationToken);
    try {
      await using NpgsqlCommand create = new(ddl.Replace("{schema}", schema, StringComparison.Ordinal), connection);
      await create.ExecuteNonQueryAsync(_cancellationToken);
      return await body(schema);
    } finally {
      await using NpgsqlCommand drop = new($"DROP SCHEMA IF EXISTS {schema} CASCADE", connection);
      await drop.ExecuteNonQueryAsync(CancellationToken.None);
    }
  }

  [Fact]
  public async Task ReadAsync_DevDatabase_ProducesALockThatWritesAndParsesBack() {
    var schema = await ReadAsync();
    SchemaLock schemaLock = new() {
      Version = 0,
      Migrations = [],
      Schemas = schema.Schemas,
      Domains = schema.Domains,
      Tables = schema.Tables,
    };

    var text = SchemaLockWriter.Write(schemaLock);
    var parsed = SchemaLockParser.Parse(text);

    Assert.NotEmpty(schema.Tables);
    Assert.NotEmpty(schema.Domains);
    Assert.Equal(text, SchemaLockWriter.Write(parsed));
    Assert.Equal(schema.Tables.Count, parsed.InsertOrder().Count);
  }

  [Fact]
  public async Task ReadAsync_DevDatabase_LeavesOutSystemAndExcludedSchemas() {
    var schema = await ReadAsync();

    Assert.DoesNotContain(schema.Tables, table => table.Name.StartsWith("pg_catalog.", StringComparison.Ordinal)
      || table.Name.StartsWith("information_schema.", StringComparison.Ordinal)
      || table.Name.StartsWith("public.", StringComparison.Ordinal));
    Assert.DoesNotContain(schema.Domains, domain => domain.Name.StartsWith("public.", StringComparison.Ordinal));
  }

  [Fact]
  public async Task ReadAsync_TablesAndDomains_AreInOrdinalNameOrder() {
    var schema = await ReadAsync();

    Assert.Equal(schema.Tables.Select(table => table.Name).Order(StringComparer.Ordinal), schema.Tables.Select(table => table.Name));
    Assert.Equal(schema.Domains.Select(domain => domain.Name).Order(StringComparer.Ordinal), schema.Domains.Select(domain => domain.Name));
  }

  [Fact]
  public async Task ReadAsync_ScratchSchema_ReadsColumnsKeysAndDomains() {
    var (schemaName, schema) = await InScratchSchemaAsync(_ScratchDdl, async name
      => (name, await ReadAsync(new() { OnlySchemas = [name] })));

    Assert.Equal([$"{schemaName}.foo", $"{schemaName}.link", $"{schemaName}.loose"], schema.Tables.Select(table => table.Name));
    var foo = schema.Tables[0];
    Assert.Equal(["foo_id"], foo.PrimaryKey);
    Assert.Equal(
      ["foo_id", "width", "area", "twice", "label", "name", "nick", "lat", "price", "amount", "prices", "tags", "seen_utc", "stamps", "fixed_utc"],
      foo.Columns.Select(column => column.Name));
    var types = foo.Columns.ToDictionary(column => column.Name, column => column.Type, StringComparer.Ordinal);
    Assert.Equal("integer", types["foo_id"]);
    Assert.Equal($"{schemaName}.name_text", types["name"]);
    Assert.Equal($"{schemaName}.coords", types["lat"]);
    Assert.Equal("decimal(12, 2)", types["price"]);
    Assert.Equal("decimal", types["amount"]);
    Assert.Equal("decimal(5, 1)[]", types["prices"]);
    Assert.Equal($"{schemaName}.tag_ids", types["tags"]);
    Assert.Equal("timestamptz", types["seen_utc"]);
    Assert.Equal("timestamptz[]", types["stamps"]);
  }

  [Fact]
  public async Task ReadAsync_ScratchSchema_ReadsGeneratedColumnsNullabilityAndPolicy() {
    var foo = (await InScratchSchemaAsync(_ScratchDdl, async name
      => await ReadAsync(new() { OnlySchemas = [name] }))).Tables[0];

    var byName = foo.Columns.ToDictionary(column => column.Name, StringComparer.Ordinal);
    Assert.Equal(GeneratedAs.IdentityAlways, byName["foo_id"].GeneratedAs);
    Assert.Equal(GeneratedAs.IdentityByDefault, byName["label"].GeneratedAs);
    Assert.Equal(GeneratedAs.ExpressionStored, byName["area"].GeneratedAs);
    Assert.Equal(GeneratedAs.ExpressionVirtual, byName["twice"].GeneratedAs);
    Assert.Null(byName["width"].GeneratedAs);
    Assert.False(byName["width"].Nullable);
    Assert.True(byName["area"].Nullable);
    Assert.False(byName["name"].Nullable);
    Assert.False(byName["nick"].Nullable);
    Assert.True(byName["lat"].Nullable);
    Assert.False(byName["width"].DeclaredNullable);
    Assert.True(byName["name"].DeclaredNullable);
    Assert.True(byName["nick"].DeclaredNullable);
    Assert.Equal(TimePolicy.Relative, byName["seen_utc"].Policy);
    Assert.Equal(TimePolicy.Relative, byName["stamps"].Policy);
    Assert.Equal(TimePolicy.Absolute, byName["fixed_utc"].Policy);
    Assert.Null(byName["width"].Policy);
  }

  [Fact]
  public async Task ReadAsync_ScratchSchema_ReadsDomainsWithBaseTypesAndChecks() {
    var (schemaName, schema) = await InScratchSchemaAsync(_ScratchDdl, async name
      => (name, await ReadAsync(new() { OnlySchemas = [name] })));

    Assert.Equal(
      [$"{schemaName}.coords", $"{schemaName}.name_text", $"{schemaName}.short_name", $"{schemaName}.tag_ids"],
      schema.Domains.Select(domain => domain.Name));
    var byName = schema.Domains.ToDictionary(domain => domain.Name, StringComparer.Ordinal);
    Assert.Equal("decimal(9, 6)", byName[$"{schemaName}.coords"].Type);
    Assert.Equal("text", byName[$"{schemaName}.name_text"].Type);
    Assert.Equal($"{schemaName}.name_text", byName[$"{schemaName}.short_name"].Type);
    Assert.Equal("smallint[]", byName[$"{schemaName}.tag_ids"].Type);
    var check = Assert.Single(byName[$"{schemaName}.coords"].Checks);
    Assert.Equal("coords_check", check.Name);
    Assert.StartsWith("CHECK (", check.Expression, StringComparison.Ordinal);
    Assert.Empty(byName[$"{schemaName}.tag_ids"].Checks);
  }

  [Fact]
  public async Task ReadAsync_ScratchSchema_ReadsCommentsDefaultsAndExpressions() {
    var (schemaName, schema) = await InScratchSchemaAsync(_ScratchDdl, async name
      => (name, await ReadAsync(new() { OnlySchemas = [name] })));

    var comment = Assert.Single(schema.Schemas);
    Assert.Equal(schemaName, comment.Name);
    Assert.Equal("Scratch things", comment.Comment);
    var foo = schema.Tables[0];
    Assert.Equal("The foo", foo.Comment);
    var byName = foo.Columns.ToDictionary(column => column.Name, StringComparer.Ordinal);
    Assert.Equal("7", byName["width"].DefaultExpression);
    Assert.Null(byName["foo_id"].DefaultExpression);
    Assert.Null(byName["foo_id"].GeneratedExpression);
    Assert.Equal("(width * 2)", byName["area"].GeneratedExpression);
    Assert.Equal("(width * 2)", byName["twice"].GeneratedExpression);
    Assert.Null(byName["area"].DefaultExpression);
    Assert.Equal("When it happened. @seed absolute", byName["fixed_utc"].Comment);
    Assert.Null(byName["width"].Comment);
    var domain = schema.Domains.Single(known => string.Equals(known.Name, $"{schemaName}.name_text", StringComparison.Ordinal));
    Assert.True(domain.NotNull);
    Assert.Equal("'x'::text", domain.DefaultExpression);
    Assert.Equal("Non-empty text", domain.Comment);
  }

  [Fact]
  public async Task ReadAsync_ScratchSchema_ReadsConstraintsAndOnlyTheIndexesThatBackNone() {
    var foo = (await InScratchSchemaAsync(_ScratchDdl, async name
      => await ReadAsync(new() { OnlySchemas = [name] }))).Tables[0];

    Assert.Equal("pk_foo", foo.PrimaryKeyName);
    var unique = Assert.Single(foo.UniqueConstraints);
    Assert.Equal("uq_foo_width", unique.Name);
    Assert.Equal(["width"], unique.Columns);
    Assert.Equal("UNIQUE (width)", unique.Definition);
    var check = Assert.Single(foo.Checks);
    Assert.Equal("ck_foo_width", check.Name);
    Assert.Equal("CHECK ((width > 0))", check.Expression);
    var index = Assert.Single(foo.Indexes);
    Assert.Equal("ix_foo_width", index.Name);
    Assert.StartsWith("CREATE INDEX ix_foo_width ON catalog_test_", index.Definition, StringComparison.Ordinal);
    Assert.EndsWith("WHERE (width > 1)", index.Definition, StringComparison.Ordinal);
  }

  [Fact]
  public async Task ReadAsync_ScratchSchema_ReadsKeysInKeyOrderAndForeignKeys() {
    var (schemaName, schema) = await InScratchSchemaAsync(_ScratchDdl, async name
      => (name, await ReadAsync(new() { OnlySchemas = [name] })));

    var link = schema.Tables[1];
    Assert.Equal(["ref_id", "foo_id"], link.PrimaryKey);
    Assert.Equal(["fk_link__foo", "fk_link__other"], link.ForeignKeys.Select(key => key.Name));
    var first = link.ForeignKeys[0];
    Assert.Equal(["foo_id"], first.Columns);
    Assert.Equal($"{schemaName}.foo", first.ReferencedTable);
    Assert.Equal(["foo_id"], first.ReferencedColumns);
    Assert.Equal(ReferentialAction.Cascade, first.OnDelete);
    Assert.Equal(ReferentialAction.Restrict, first.OnUpdate);
    Assert.True(first.Deferrable);
    Assert.True(first.InitiallyDeferred);
    var second = link.ForeignKeys[1];
    Assert.Equal(ReferentialAction.SetNull, second.OnDelete);
    Assert.Equal(ReferentialAction.NoAction, second.OnUpdate);
    Assert.False(second.Deferrable);
    Assert.Empty(schema.Tables[2].PrimaryKey);
  }


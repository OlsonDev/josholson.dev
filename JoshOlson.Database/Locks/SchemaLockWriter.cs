using System.Text.Encodings.Web;
using System.Text.Json;
using JoshOlson.Database.Schema;
using JoshOlson.Shared.Extensions;

namespace JoshOlson.Database.Locks;

// Writes the lock in its one canonical form, so an unchanged lock is byte-for-byte unchanged and a diff shows only real
// changes. LF line endings, a final newline, migrations by version, schemas, domains, and tables by name, columns in
// catalog order, the primary key in key order, everything else in a table by name. A key that has its default value
// (`nullable: false`, `on_delete: no-action`) or no value (no comment, no default) is left out.
//
//   version: 42
//   migrations:
//     - version: 1
//       file: V001__foo.sql
//       checksum: <sha-256>
//       accepted_checksums:        # only when an edit was accepted
//         - <sha-256>
//   schemas:                                         # only schemas that have a comment
//     foo: Comment text
//   domains:                                         # only when there are some
//     foo.grault:
//       type: decimal(9, 6)
//       not_null: true
//       default_expression: "0.000000::numeric"
//       comment: Comment text
//       checks:
//         - { name: grault_range, expression: "CHECK ((VALUE >= ...))" }
//   tables:
//     foo.bar:
//       comment: Comment text
//       columns:
//         - { name: bar_id, type: bigint, generated_as: identity-always }
//         - { name: baz, type: foo.grault, nullable: true, default_expression: "0.000000::numeric", comment: Comment text }
//         - { name: qux_utc, type: timestamptz, policy: relative }
//         - { name: corge, type: "smallint[]" }      # `[`, `]` and `,` are flow indicators, so those types are quoted
//         - { name: area, type: integer, generated_as: expression-stored, generated_expression: "(baz * 2)" }
//       primary_key: [bar_id]
//       primary_key_name: pk_bar
//       unique:
//         - { name: uq_bar_baz, columns: [baz], definition: "UNIQUE (baz)" }
//       checks:
//         - { name: ck_bar_baz, expression: "CHECK ((baz > 0))" }
//       foreign_keys:
//         - { name: fk_bar_grault, columns: [baz], references: foo.grault, referenced_columns: [slug], on_delete: cascade }
//       indexes:
//         - { name: ix_bar_baz, definition: "CREATE INDEX ix_bar_baz ON foo.bar USING btree (baz)" }
public static class SchemaLockWriter {
  public const string Header = "# Generated by the seed tool. Never edit by hand (ADR 0034, lock file and branch-safe migration).";

  // Relaxed escaping keeps `'` and `<` readable in a check expression; JSON string syntax is valid YAML either way.
  private static readonly JsonSerializerOptions _QuotedScalar = new() { Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping };

  public static string Write(SchemaLock schemaLock) {
    List<string> lines = [
      Header,
      FormattableString.Invariant($"version: {schemaLock.Version}"),
    ];
    WriteMigrations(lines, schemaLock.Migrations);
    if (schemaLock.Schemas.Count > 0) {
      lines.Add("schemas:");
      lines.AddRange(schemaLock.Schemas.Select(schema => $"  {Scalar(schema.Name)}: {Scalar(schema.Comment)}"));
    }
    if (schemaLock.Domains.Count > 0) {
      lines.Add("domains:");
      foreach (var domain in schemaLock.Domains) {
        WriteDomain(lines, domain);
      }
    }
    if (schemaLock.Tables.Count is 0) {
      lines.Add("tables: {}");
    } else {
      lines.Add("tables:");
      foreach (var table in schemaLock.Tables) {
        WriteTable(lines, table);
      }
    }
    return string.Join('\n', lines) + '\n';
  }

  private static void WriteMigrations(List<string> lines, List<LockedMigration> migrations) {
    if (migrations.Count is 0) {
      lines.Add("migrations: []");
      return;
    }
    lines.Add("migrations:");
    foreach (var migration in migrations) {
      lines.Add(FormattableString.Invariant($"  - version: {migration.Version}"));
      lines.Add($"    file: {Scalar(migration.File)}");
      lines.Add($"    checksum: {Scalar(migration.Checksum)}");
      if (migration.AcceptedChecksums.Count > 0) {
        lines.Add("    accepted_checksums:");
        lines.AddRange(migration.AcceptedChecksums.Select(checksum => $"      - {Scalar(checksum)}"));
      }
    }
  }

  private static void WriteDomain(List<string> lines, Domain domain) {
    lines.Add($"  {Scalar(domain.Name)}:");
    lines.Add($"    type: {Scalar(domain.Type)}");
    if (domain.NotNull) {
      lines.Add("    not_null: true");
    }
    if (domain.DefaultExpression is not null) {
      lines.Add($"    default_expression: {Scalar(domain.DefaultExpression)}");
    }
    if (domain.Comment is not null) {
      lines.Add($"    comment: {Scalar(domain.Comment)}");
    }
    AddList(lines, "    checks:", domain.Checks.Select(Check));
  }

  private static void WriteTable(List<string> lines, Table table) {
    lines.Add($"  {Scalar(table.Name)}:");
    if (table.Comment is not null) {
      lines.Add($"    comment: {Scalar(table.Comment)}");
    }
    lines.Add("    columns:");
    lines.AddRange(table.Columns.Select(ColumnLine));
    if (table.PrimaryKey.Count > 0) {
      lines.Add($"    primary_key: {Names(table.PrimaryKey)}");
    }
    if (table.PrimaryKeyName is not null) {
      lines.Add($"    primary_key_name: {Scalar(table.PrimaryKeyName)}");
    }
    AddList(lines, "    unique:", table.UniqueConstraints.Select(UniqueLine));
    AddList(lines, "    checks:", table.Checks.Select(Check));
    AddList(lines, "    foreign_keys:", table.ForeignKeys.Select(ForeignKeyLine));
    AddList(lines, "    indexes:", table.Indexes.Select(IndexLine));
  }

  // The key and its items, left out when there are none.
  private static void AddList(List<string> lines, string key, IEnumerable<string> items) {
    var list = items.ToList();
    if (list.Count > 0) {
      lines.Add(key);
      lines.AddRange(list);
    }
  }

  private static string ColumnLine(Column column) {
    List<string> parts = [
      $"name: {Scalar(column.Name)}",
      $"type: {Scalar(column.Type)}",
    ];
    if (column.Nullable) {
      parts.Add("nullable: true");
    }
    if (column.DeclaredNullable && !column.Nullable) {
      parts.Add("declared_nullable: true");
    }
    if (column.GeneratedAs is { } generatedAs) {
      parts.Add($"generated_as: {generatedAs.ToKebabCase()}");
    }
    if (column.GeneratedExpression is not null) {
      parts.Add($"generated_expression: {Scalar(column.GeneratedExpression)}");
    }
    if (column.DefaultExpression is not null) {
      parts.Add($"default_expression: {Scalar(column.DefaultExpression)}");
    }
    if (column.Policy is { } policy) {
      parts.Add($"policy: {policy.ToKebabCase()}");
    }
    if (column.Comment is not null) {
      parts.Add($"comment: {Scalar(column.Comment)}");
    }
    return Flow(parts);
  }

  private static string UniqueLine(UniqueConstraint constraint)
    => Flow([
      $"name: {Scalar(constraint.Name)}",
      $"columns: {Names(constraint.Columns)}",
      $"definition: {Scalar(constraint.Definition)}",
    ]);

  private static string Check(CheckConstraint check)
    => Flow([
      $"name: {Scalar(check.Name)}",
      $"expression: {Scalar(check.Expression)}",
    ]);

  private static string IndexLine(TableIndex index)
    => Flow([
      $"name: {Scalar(index.Name)}",
      $"definition: {Scalar(index.Definition)}",
    ]);

  private static string ForeignKeyLine(ForeignKey key) {
    List<string> parts = [
      $"name: {Scalar(key.Name)}",
      $"columns: {Names(key.Columns)}",
      $"references: {Scalar(key.ReferencedTable)}",
      $"referenced_columns: {Names(key.ReferencedColumns)}",
    ];
    if (key.OnDelete is not ReferentialAction.NoAction) {
      parts.Add($"on_delete: {key.OnDelete.ToKebabCase()}");
    }
    if (key.OnUpdate is not ReferentialAction.NoAction) {
      parts.Add($"on_update: {key.OnUpdate.ToKebabCase()}");
    }
    if (key.Deferrable) {
      parts.Add("deferrable: true");
    }
    if (key.InitiallyDeferred) {
      parts.Add("deferred: true");
    }
    return Flow(parts);
  }

  // One list item as a flow mapping, indented to sit under a table's key.
  private static string Flow(List<string> parts)
    => $"      - {{ {string.Join(", ", parts)} }}";

  private static string Names(List<string> names)
    => $"[{string.Join(", ", names.Select(Scalar))}]";

  // Plain when it is a simple word, otherwise a double-quoted scalar (JSON string syntax is valid YAML).
  private static string Scalar(string value)
    => value.Length > 0
      && (char.IsAsciiLetterOrDigit(value[0]) || value[0] is '_')
      && value.All(character => char.IsAsciiLetterOrDigit(character) || character is '_' or '.' or '-')
      ? value
      : JsonSerializer.Serialize(value, _QuotedScalar);
}
